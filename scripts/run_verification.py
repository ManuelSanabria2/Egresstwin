"""Run every simulator verification case and write the report.

Generates figures in docs/figures/verification/, the human report in
docs/verification/report.md, and the machine-readable status in
docs/verification/status.json (consumed by the agent report and UI).
No network, no API cost.

Usage: python scripts/run_verification.py [--replicas N] [--seed S]
"""

from __future__ import annotations

import argparse
import json
import os
import time
from pathlib import Path

os.environ.setdefault(
    "MPLCONFIGDIR", str(Path(__file__).resolve().parents[1] / "runs" / "mplconfig")
)

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from egresstwin.validation.cases import CaseResult, run_all

ROOT = Path(__file__).resolve().parents[1]
FIG_DIR = ROOT / "docs" / "figures" / "verification"
DOC_DIR = ROOT / "docs" / "verification"


def _plot(case: CaseResult) -> None:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    data = case.data
    fig, ax = plt.subplots(figsize=(7, 4))
    if case.id == "V1":
        times = data["times"]
        ax.bar(range(1, len(times) + 1), times)
        ax.axhspan(26, 34, color="green", alpha=0.15, label="RiMEA band 26-34 s")
        ax.set_xlabel("replica")
        ax.set_ylabel("travel time (s)")
    elif case.id == "V2":
        walk = data["walkable"]
        ax.imshow(walk, cmap="Greys", origin="upper")
        frames = data["frames"].astype(np.float64)
        cell = 0.25
        for i in range(frames.shape[1]):
            path = frames[:, i, :]
            path = path[path[:, 0] >= 0]
            if len(path) > 1:
                ax.plot(path[:, 0] / cell, path[:, 1] / cell, lw=0.7, alpha=0.6)
        ax.set_xlabel("grid column")
        ax.set_ylabel("grid row")
    elif case.id == "V3":
        ax.scatter(data["delays"], data["observed"], zorder=3)
        lims = [0, 110]
        ax.plot(lims, lims, color="green", lw=1, label="observed = assigned")
        ax.set_xlabel("assigned reaction time (s)")
        ax.set_ylabel("observed first movement (s)")
        ax.legend()
    elif case.id == "V4":
        t = np.arange(len(data["dens1"])) * data["frame_dt"]
        ax.plot(t, data["dens1"], label="room 1 (before bottleneck)")
        ax.plot(t, data["dens2"], label="room 2 (after bottleneck)")
        ax.set_xlabel("time (s)")
        ax.set_ylabel("occupancy density (people/m^2)")
        ax.legend()
    elif case.id == "V5":
        s1, s2 = data["shares"]
        ax.bar(["E1 (near)", "E2 (far)"], [s1 * 100, s2 * 100])
        ax.set_ylabel("share of people (%)")
    elif case.id == "V6":
        rho = np.linspace(0.05, 3.0, 100)
        from egresstwin.validation.cases import weidmann_speed

        ax.plot(rho, [weidmann_speed(r) for r in rho], color="green",
                label="Weidmann (1993)")
        ax.scatter(data["centres"], data["means"], color="darkred",
                   zorder=3, label="simulated (binned means)")
        ax.set_xlabel("local density (people/m^2)")
        ax.set_ylabel("mean speed (m/s)")
        ax.legend()
    ax.set_title(f"{case.id} - {case.title}")
    fig.savefig(FIG_DIR / case.figure, dpi=130, bbox_inches="tight")
    plt.close(fig)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--replicas", type=int, default=3)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    started = time.perf_counter()
    results = run_all(replicas=args.replicas, seed=args.seed)
    for case in results:
        _plot(case)
        print(f"{case.id} {'PASS' if case.passed else 'FAIL'} "
              f"{case.title}: {case.detail}")

    DOC_DIR.mkdir(parents=True, exist_ok=True)
    n_pass = sum(c.passed for c in results)
    status = {
        "available": True,
        "passed": n_pass,
        "total": len(results),
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "seed": args.seed,
        "report": "docs/verification/report.md",
        "cases": [
            {"id": c.id, "title": c.title, "passed": c.passed}
            for c in results
        ],
    }
    (DOC_DIR / "status.json").write_text(
        json.dumps(status, indent=2), encoding="utf-8"
    )
    (DOC_DIR / "results.json").write_text(
        json.dumps([c.as_dict() for c in results], indent=2), encoding="utf-8"
    )

    lines = [
        "# Simulator verification report",
        "",
        "Generated by `python scripts/run_verification.py` "
        f"(seed {args.seed}). Case definitions and sources: "
        "[test_cases.md](test_cases.md). A failing case is reported "
        "as-is, with a technical explanation; nothing is tuned after "
        "seeing results.",
        "",
        f"**{n_pass} of {len(results)} standard cases passed.**",
        "",
        "| Case | Source | Criterion | Result | Status | Figure |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for c in results:
        result_txt = "; ".join(
            f"{k}={v}" for k, v in c.metrics.items()
        )[:160]
        lines.append(
            f"| {c.id} {c.title} | {c.source} | {c.criterion} | "
            f"{result_txt} | {'PASS' if c.passed else 'FAIL'} | "
            f"[figure](../figures/verification/{c.figure}) |"
        )
    lines += ["", "## Detail", ""]
    for c in results:
        lines += [
            f"### {c.id} - {c.title}",
            "",
            f"- Source: {c.source}",
            f"- Criterion: {c.criterion}",
            f"- Status: **{'PASS' if c.passed else 'FAIL'}**",
            f"- Metrics: `{json.dumps(c.metrics)}`",
            f"- Explanation: {c.detail}",
            f"- Figure: [{c.figure}](../figures/verification/{c.figure})",
            "",
        ]
    (DOC_DIR / "report.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"\n{n_pass}/{len(results)} passed in "
          f"{time.perf_counter() - started:.1f} s. "
          f"Report: docs/verification/report.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
