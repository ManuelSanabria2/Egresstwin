"""Total project API cost from the run ledgers.

Reads runs/costs.jsonl (production client) and, when present,
runs/spikes/costs_spike.jsonl (the P01 spike ledger kept separately),
and writes docs/cost_report.md. Mock-mode calls are counted apart:
they cost nothing by construction.

Usage: python scripts/cost_report.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _read_ledger(path: Path) -> list[dict]:
    if not path.is_file():
        return []
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            rows.append(json.loads(line))
    return rows


def main() -> int:
    ledgers = {
        "Production client (runs/costs.jsonl)": _read_ledger(ROOT / "runs" / "costs.jsonl"),
        "P01 spike (runs/spikes/costs_spike.jsonl)": _read_ledger(
            ROOT / "runs" / "spikes" / "costs_spike.jsonl"
        ),
    }
    lines = [
        "# Project API cost report",
        "",
        "Generated by `python scripts/cost_report.py` from the run "
        "ledgers. Every charged Meta Model API call is logged there "
        "by `meta/client.py`; mock-mode calls are free by "
        "construction and are counted separately.",
        "",
    ]
    grand_real = 0.0
    for title, rows in ledgers.items():
        real = [r for r in rows if not r.get("mock")]
        mock = [r for r in rows if r.get("mock")]
        real_total = sum(float(r.get("cost_usd", 0.0)) for r in real)
        mock_total = sum(float(r.get("cost_usd", 0.0)) for r in mock)
        grand_real += real_total
        by_kind: dict[str, float] = {}
        for r in real:
            by_kind[r.get("kind", "?")] = by_kind.get(r.get("kind", "?"), 0.0) + float(
                r.get("cost_usd", 0.0)
            )
        lines += [
            f"## {title}",
            "",
            f"- Real calls: {len(real)} totalling USD {real_total:.4f}",
            f"- Mock calls: {len(mock)} (notional USD {mock_total:.4f}, charged 0)",
        ]
        for kind, total in sorted(by_kind.items()):
            lines.append(f"- Real spend on {kind}: USD {total:.4f}")
        lines.append("")
    lines += [
        f"**Total ledger-backed real API spend: USD {grand_real:.4f}.**",
        "",
        "PROGRESS.md (P01 entry) additionally records about "
        "USD 0.0133 of exploratory probes that were not written to "
        "either ledger, putting the all-in project spend at about "
        "USD 0.08. The spike cap was USD 2; the production budget "
        "guard META_BUDGET_USD defaults to USD 60.",
    ]
    out = ROOT / "docs" / "cost_report.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
